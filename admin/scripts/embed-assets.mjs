import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, extname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const dist = join(root, 'admin', 'dist');
const contentTypes = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
  '.woff2': 'font/woff2',
};
const assets = Object.create(null);
async function collect(directory) {
  const entries = (await readdir(directory, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name));
  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) await collect(path);
    else if (entry.isFile()) {
      const contentType = contentTypes[extname(entry.name)];
      if (!contentType) throw new Error(`Unsupported admin asset: ${entry.name}`);
      const key = '/' + relative(dist, path).replaceAll('\\', '/');
      assets[key] = { contentType, body: (await readFile(path)).toString('base64') };
    }
  }
}
await collect(dist);
if (!assets['/index.html']) throw new Error('Admin build has no index.html');
await writeFile(join(root, 'admin-assets.cjs'), "'use strict';\n// Generated by npm --prefix admin run build. Do not edit directly.\nmodule.exports = " + JSON.stringify(assets, null, 2) + ';\n');
console.log(`Embedded ${Object.keys(assets).length} admin assets in admin-assets.cjs`);
